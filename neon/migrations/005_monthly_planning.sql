CREATE TABLE public.monthly_plan_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  month DATE NOT NULL CHECK (extract(day FROM month) = 1),
  source_key TEXT NOT NULL,
  transaction_id UUID REFERENCES public.transactions(id) ON DELETE SET NULL,
  UNIQUE(user_id, month, source_key),
  UNIQUE(transaction_id)
);
ALTER TABLE public.monthly_plan_items ENABLE ROW LEVEL SECURITY;
CREATE POLICY owner_access ON public.monthly_plan_items TO authenticated USING (user_id::text = auth.user_id());
GRANT SELECT ON public.monthly_plan_items TO authenticated;
REVOKE ALL ON public.monthly_plan_items FROM PUBLIC, anonymous;
ALTER TABLE public.transactions ADD COLUMN planning_item_id UUID REFERENCES public.monthly_plan_items(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX transactions_planning_item_unique ON public.transactions(planning_item_id) WHERE planning_item_id IS NOT NULL;

CREATE FUNCTION public.prepare_financial_month(target_month DATE) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid UUID := auth.user_id()::uuid; first_day DATE; last_day INT;
  p public.financial_profile%ROWTYPE; source RECORD; item_id UUID; tx_id UUID; created_count INT := 0;
  extras JSONB; extra_total NUMERIC;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'Não autenticado' USING ERRCODE='42501'; END IF;
  IF target_month IS NULL THEN RAISE EXCEPTION 'Selecione um mês'; END IF;
  first_day := date_trunc('month',target_month)::date;
  last_day := extract(day FROM first_day + interval '1 month - 1 day');
  PERFORM pg_advisory_xact_lock(hashtext(uid::text || first_day::text));
  SELECT * INTO p FROM public.financial_profile WHERE id=uid;
  IF NOT FOUND THEN RAISE EXCEPTION 'Configure sua renda e suas contas antes de preparar o mês'; END IF;
  extras := COALESCE(p.onboarding_data->'extraIncomes','[]'::jsonb);
  IF jsonb_typeof(extras) <> 'array' THEN extras := '[]'::jsonb; END IF;
  SELECT COALESCE(sum(GREATEST((e->>'amount')::numeric,0)),0) INTO extra_total FROM jsonb_array_elements(extras) e;
  FOR source IN
    SELECT 'salary'::text key, 'Salário previsto'::text title, 'Salário'::text category,
      GREATEST(COALESCE(p.monthly_income,0)-extra_total,0)::numeric amount, COALESCE(p.pay_day,1) due_day
    UNION ALL
    SELECT 'extra:' || (e->>'label'), e->>'label', 'Renda extra', (e->>'amount')::numeric, COALESCE(p.pay_day,1)
      FROM jsonb_array_elements(extras) e WHERE (e->>'amount')::numeric > 0
    UNION ALL
    SELECT 'fixed:' || f.id::text, f.title, f.category, -f.amount, f.due_day
      FROM public.fixed_expenses f WHERE f.user_id=uid AND f.is_active
  LOOP
    IF source.amount = 0 THEN CONTINUE; END IF;
    INSERT INTO public.monthly_plan_items(user_id,month,source_key) VALUES(uid,first_day,source.key)
      ON CONFLICT(user_id,month,source_key) DO NOTHING RETURNING id INTO item_id;
    -- Deleted / ignored forecasts are not regenerated by repeated preparation.
    IF item_id IS NULL THEN CONTINUE; END IF;
    INSERT INTO public.transactions(user_id,title,category,amount,date,competency_date,payment_method,is_paid,is_ignored,transaction_kind,origin,settlement_status,planning_item_id,description)
    VALUES(uid,source.title,source.category,source.amount,first_day + LEAST(source.due_day,last_day)-1,first_day,
      'Transferência',false,false,CASE WHEN source.amount > 0 THEN 'income' ELSE 'expense' END,'automatic','pending',item_id,
      'Previsão do planejamento mensal. Confirme recebimento ou pagamento, ou vincule um lançamento existente.') RETURNING id INTO tx_id;
    UPDATE public.monthly_plan_items SET transaction_id=tx_id WHERE id=item_id;
    created_count := created_count + 1;
  END LOOP;
  RETURN created_count;
END $$;

CREATE FUNCTION public.link_planned_transaction(plan_id UUID, existing_id UUID) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid UUID := auth.user_id()::uuid; item public.monthly_plan_items%ROWTYPE;
  forecast public.transactions%ROWTYPE; existing public.transactions%ROWTYPE;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'Não autenticado' USING ERRCODE='42501'; END IF;
  SELECT * INTO item FROM public.monthly_plan_items WHERE id=plan_id AND user_id=uid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Previsão não encontrada'; END IF;
  SELECT * INTO forecast FROM public.transactions WHERE id=item.transaction_id AND user_id=uid FOR UPDATE;
  IF NOT FOUND OR forecast.is_paid OR forecast.is_ignored THEN RAISE EXCEPTION 'Apenas previsões pendentes podem ser vinculadas'; END IF;
  SELECT * INTO existing FROM public.transactions WHERE id=existing_id AND user_id=uid FOR UPDATE;
  IF NOT FOUND OR existing.id=forecast.id OR existing.planning_item_id IS NOT NULL OR existing.is_ignored
    OR date_trunc('month',COALESCE(existing.competency_date,existing.date))::date <> item.month
    OR sign(existing.amount) <> sign(forecast.amount) THEN RAISE EXCEPTION 'Escolha um lançamento do mesmo mês e tipo, ainda não vinculado'; END IF;
  UPDATE public.monthly_plan_items SET transaction_id=existing.id WHERE id=item.id;
  DELETE FROM public.transactions WHERE id=forecast.id;
  UPDATE public.transactions SET planning_item_id=item.id WHERE id=existing.id;
END $$;
REVOKE ALL ON FUNCTION public.prepare_financial_month(DATE), public.link_planned_transaction(UUID,UUID) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.prepare_financial_month(DATE), public.link_planned_transaction(UUID,UUID) TO authenticated;

-- Browsers can edit financial fields, but only the RPC can assign planning links.
REVOKE INSERT, UPDATE ON public.transactions FROM authenticated;
DO $$ DECLARE fields TEXT; BEGIN
  SELECT string_agg(quote_ident(column_name),',') INTO fields FROM information_schema.columns
    WHERE table_schema='public' AND table_name='transactions' AND column_name <> 'planning_item_id';
  EXECUTE 'GRANT INSERT (' || fields || '), UPDATE (' || fields || ') ON public.transactions TO authenticated';
END $$;

-- Keep plan links consistent when a user resets their own financial data.
CREATE OR REPLACE FUNCTION public.restore_financial_data() RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid UUID := auth.user_id()::uuid;
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'Não autenticado' USING ERRCODE='42501'; END IF;
  DELETE FROM public.transactions WHERE user_id=uid;
  DELETE FROM public.monthly_plan_items WHERE user_id=uid;
  DELETE FROM public.credit_card_invoice_items WHERE user_id=uid;
  DELETE FROM public.credit_card_invoices WHERE user_id=uid;
  DELETE FROM public.credit_cards WHERE user_id=uid;
  DELETE FROM public.budgets WHERE user_id=uid;
  DELETE FROM public.fixed_expenses WHERE user_id=uid;
  DELETE FROM public.accounts WHERE user_id=uid;
  DELETE FROM public.files WHERE user_id=uid AND kind='attachment';
  UPDATE public.financial_profile SET monthly_income=0,pay_day=1,onboarding_completed_at=NULL,onboarding_data=NULL,updated_at=now() WHERE id=uid;
END $$;
